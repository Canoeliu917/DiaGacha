function copySentenceV39(text) {
  const value = String(text || '').trim();
  return value && !/[。！？][”’」』"]?$/.test(value) ? `${value.replace(/[；，]+$/, '')}。` : value;
}

function stageSentenceV39(text) {
  return copySentenceV39(String(text || '').replace(/^排演时[，,：:]\s*/, ''));
}

