function applyCopyOverridesV39(cards, essays) {
  for (const card of cards) {
    const patch = copyOverridesV39[card.id];
    if (!patch) continue;
    const { essay, ...fields } = patch;
    Object.assign(card, fields);
    if (Object.hasOwn(fields, 'note')) {
      card.blurb = fields.note;
      if (card.dimension === '剧目') card.plot = fields.note;
    }
    if (Object.hasOwn(fields, 'observe')) card.why = fields.observe;
    if (Object.hasOwn(fields, 'stage')) {
      card.hook = card.with = fields.stage;
      card.action = fields.stage.replace(/[。；]+$/, '');
    }
    if (Object.hasOwn(patch, 'essay')) essays[card.id] = essay;
  }
}

if (typeof module !== 'undefined' && module.exports) module.exports = { copyOverridesV39, applyCopyOverridesV39 };
